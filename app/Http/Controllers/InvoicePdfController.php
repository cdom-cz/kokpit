<?php

declare(strict_types=1);

namespace App\Http\Controllers;

use App\Domain\Documents\Models\Document;
use App\Domain\Documents\Support\DocumentDisposition;
use App\Domain\Invoicing\Models\Invoice;
use App\Domain\Invoicing\Models\InvoiceAdmin;
use App\Domain\Shared\Auth\PartnerContext;
use App\Domain\Shared\Models\Media;
use Illuminate\Filesystem\FilesystemAdapter;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Gate;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;
use Symfony\Component\HttpFoundation\StreamedResponse;

/**
 * Streams the stored PDF of an issued document to the signed-in user (IN-09, IN-04, D-21; ruling R-38-1). The route
 * is signed, short-lived and inside the panel's authentication, like the file route. The PDF is reached through the
 * invoice, never through the Document scope, and the order of the checks is fixed so that a foreign invoice, a
 * draft, an unknown id and a document without a PDF cannot be told apart (all 404):
 *
 * 1. the user id under the signature is the signed-in user (403),
 * 2. the id has the shape of a UUID (404),
 * 3. the invoice is found through the Partner-scoped query (404) and is issued (404; the Admin's query also holds drafts),
 * 4. the policy allows `view` (403),
 * 5. as system, the PDF link of the Admin-only row is read, and nothing else of that row leaves this method (404 when empty),
 * 6. the linked document is loaded only when the invoice owns it (404),
 * 7. the media row is read as system, because Media is closed to Partners (404 when missing).
 *
 * The bytes are streamed by the application. No bucket URL, presigned URL or storage path reaches the browser.
 * The PDF is generated by the application, but `nosniff` and `private, no-store` are sent all the same.
 */
final class InvoicePdfController
{
    public function __invoke(Request $request, PartnerContext $context, string $invoice): StreamedResponse
    {
        $user = $request->user();

        abort_unless($user !== null && $request->query('u') === $user->getKey(), 403);
        abort_unless(Str::isUuid($invoice), 404);

        $record = Invoice::query()->whereKey($invoice)->first();

        abort_if($record === null || ! $record->isIssued(), 404);

        Gate::authorize('view', $record);

        /** @var array{0: Document, 1: Media}|null $stored */
        $stored = $context->runAsSystem(static function () use ($record): ?array {
            $documentId = InvoiceAdmin::query()->where('invoice_id', $record->getKey())->value('pdf_document_id');

            if (! is_string($documentId)) {
                return null;
            }

            // The owner is checked here as well as by the database guard, so the route does not rely on one alone.
            $document = Document::query()
                ->whereKey($documentId)
                ->where('owner_type', 'invoice')
                ->where('owner_id', $record->getKey())
                ->first();

            if ($document === null) {
                return null;
            }

            $media = Media::query()
                ->where('model_type', 'document')
                ->where('model_id', $document->getKey())
                ->first();

            return $media === null ? null : [$document, $media];
        });

        abort_if($stored === null, 404);

        [$document, $media] = $stored;

        /** @var FilesystemAdapter $disk */
        $disk = Storage::disk($media->disk);
        $path = $media->getPathRelativeToRoot();

        // A row without its object is a missing file, not a half-sent response.
        abort_unless($disk->exists($path), 404);

        return $disk->response($path, null, [
            'Content-Type' => $document->mime_type === 'application/pdf' ? 'application/pdf' : DocumentDisposition::DOWNLOAD_MIME_TYPE,
            'Content-Length' => (string) $document->size_bytes,
            'Content-Disposition' => DocumentDisposition::header('attachment', DocumentDisposition::downloadName($document)),
            'X-Content-Type-Options' => 'nosniff',
            'Cache-Control' => 'private, no-store',
        ]);
    }
}
